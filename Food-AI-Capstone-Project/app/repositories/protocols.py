from typing import Protocol

from sqlalchemy.orm import Session

from app.models import ChatMessage, ChatSession, Document, MenuItem, Order, PendingAction, User


class UserRepository(Protocol):
    def by_username(self, username: str) -> User | None: ...

    def add(self, user: User) -> User: ...


class MenuRepository(Protocol):
    def search(
        self,
        *,
        category: str | None = None,
        vegetarian: bool | None = None,
        max_price: float | None = None,
        keyword: str | None = None,
        active_only: bool = True,
    ) -> list[MenuItem]: ...

    def get(self, item_id: int, *, for_update: bool = False) -> MenuItem | None: ...

    def get_many_for_update(self, item_ids: list[int]) -> list[MenuItem]: ...

    def add(self, item: MenuItem) -> MenuItem: ...


class OrderRepository(Protocol):
    def lock_user(self, user_id: int) -> None: ...

    def by_idempotency_key(self, user_id: int, key: str) -> Order | None: ...

    def get(self, order_id: int, *, for_update: bool = False) -> Order | None: ...

    def list_for_user(self, user_id: int) -> list[Order]: ...

    def list_all(self) -> list[Order]: ...


class ChatRepository(Protocol):
    def create_session(self, user_id: int, title: str) -> ChatSession: ...

    def session_for_owner(
        self, session_id: int, user_id: int, *, for_update: bool = False
    ) -> ChatSession | None: ...

    def list_sessions(self, user_id: int) -> list[ChatSession]: ...

    def messages(self, session_id: int, limit: int = 20) -> list[ChatMessage]: ...

    def add_message(
        self, session: ChatSession, role: str, content: str, *, mode: str | None = None,
        metadata: dict | None = None, touch_session: bool = True
    ) -> ChatMessage: ...

    def add_pending_action(self, action: PendingAction) -> PendingAction: ...

    def pending_action(
        self, action_id: int, user_id: int, *, for_update: bool = False
    ) -> PendingAction | None: ...

    def pending_actions(self, session_id: int, user_id: int) -> list[PendingAction]: ...


class DocumentRepository(Protocol):
    def latest_named(self, filename: str) -> Document | None: ...

    def add(self, document: Document) -> Document: ...

    def active_documents(self) -> list[Document]: ...

    def by_id(self, document_id: int) -> Document | None: ...


class VectorStore(Protocol):
    def upsert_document(self, **kwargs) -> None: ...

    def deactivate_document(self, document_id: int) -> None: ...

    def search(self, embedding: list[float], limit: int = 4) -> list[dict]: ...


class GeminiGateway(Protocol):
    async def generate(self, contents: list[dict], **kwargs) -> dict: ...

    async def embed(self, text: str, *, task_type: str) -> list[float]: ...


class RepositoryFactory(Protocol):
    def users(self, session: Session) -> UserRepository: ...